"""One command to (re)generate ALL paper outputs from whatever is in data/results/.

  * Figures -> figures/*.png
  * Tables  -> generated/*.tex   (LaTeX; the paper can \\input these)

It always uses the NEWEST file per (cue, model, category), so it simply reflects the
current data and is safe to re-run at any time. Missing pieces are skipped, not fatal.

generated/*.tex are convenience previews with a quick trial-level bootstrap; the
paper's CIs come from make_paper_numbers.py.

    python src/make_paper_outputs.py

Depends only on numpy/pandas/matplotlib (no scipy).
"""
from __future__ import annotations

import glob
import os
import re
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(__file__))
from analysis import (empirical_curve, load_results, local_crossing_bootstrap,  # noqa: E402
                      local_crossing_wtp, position_controlled_bootstrap,
                      position_controlled_wtp)

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
RESULTS = os.path.join(ROOT, "data", "results")
FIGS = os.path.join(ROOT, "figures")
GEN = os.path.join(ROOT, "generated")

# nova-pro (excluded in the paper) is kept so its runs can be inspected.
_ALIASES = ["gpt-4o-mini", "gpt-4o", "claude-sonnet", "claude-haiku",
            "nova-pro", "nova-micro", "llama-70b", "llama-8b", "mock"]
_ALT = "|".join(re.escape(a) for a in _ALIASES)
MODEL_RE = re.compile(r"_(" + _ALT + r")_\d")
TEAL, WARN, INK, MUTED, GRID = "#0F766E", "#B4432F", "#1E2A33", "#6B7480", "#E5EAEC"


# ---------- discovery ----------
def _model_of(fn):
    m = MODEL_RE.search(fn)
    return m.group(1) if m else None


def _cue_of(fn):
    b = os.path.basename(fn)
    b = re.sub(r"^(m4_|e1_|add_)", "", b)
    b = re.sub(r"_(" + _ALT + r")_\d.*$", "", b)
    return b


def newest_by(pattern, key):
    """Map key(fn) -> newest matching file (skips mock)."""
    out = {}
    for f in sorted(glob.glob(pattern, recursive=True)):
        if "_mock_" in os.path.basename(f):
            continue
        out[key(f)] = f  # sorted asc -> newest stamp wins
    return out


def pe_row(df, n_boot=300):
    pc = position_controlled_wtp(df)
    lc = local_crossing_wtp(df) * 100
    cb = local_crossing_bootstrap(df, n_boot=n_boot)
    base = df[df["price_gap"] == 0]["chose_nudged"].mean()
    return {
        "base0": float(base), "logistic": pc["wtp"] * 100, "local": lc,
        "lo": cb["ci95"][0] * 100, "hi": cb["ci95"][1] * 100,
        "b0": pc["b0"], "b_gap": pc["b_gap"], "b_pos": pc["b_pos"], "n": len(df),
    }


# ---------- tables ----------
def write_tex(name, header, rows, caption, label):
    os.makedirs(GEN, exist_ok=True)
    cols = "l" + "r" * (len(header) - 1)
    lines = [f"% auto-generated by make_paper_outputs.py -- do not edit",
             "\\begin{table}[t]\\centering", f"\\caption{{{caption}}}\\label{{{label}}}",
             f"\\begin{{tabular}}{{{cols}}}", "\\toprule",
             " & ".join(header) + " \\\\", "\\midrule"]
    for r in rows:
        lines.append(" & ".join(str(c) for c in r) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    with open(os.path.join(GEN, name), "w") as f:
        f.write("\n".join(lines))
    print(f"  wrote {os.path.join('generated', name)}  ({len(rows)} rows)")


def cue_price_table(model="gpt-4o", category="headphones"):
    sub = "M4_validity" if category == "headphones" else f"M4_validity_{category}"
    files = newest_by(os.path.join(RESULTS, sub, "**", f"m4_*_{model}_*.csv"), _cue_of)
    if not files:
        return
    order = ["sp_weak", "sp_medium", "sp_strong", "sp_vstrong", "scarcity", "authority",
             "neutral", "vacuous", "presence_ctrl", "sp_strong_lenctrl",
             "framing_pct_frac", "framing_rating", "framing_gainloss",
             "neutral_color", "neutral_manual", "neutral_barcode", "neutral_eco"]
    rows = []
    for cue in [c for c in order if c in files] + [c for c in files if c not in order]:
        r = pe_row(load_results(files[cue]))
        flag = " *" if abs(r["b_pos"]) > 8 else ""
        rows.append([cue.replace("_", "\\_"), f"{r['base0']:.2f}",
                     f"{r['local']:.1f}", f"[{r['lo']:.1f}, {r['hi']:.1f}]",
                     f"{r['b0']:.2f}", f"{r['b_gap']:.1f}{flag}"])
    write_tex(f"tab_cue_prices_{category}.tex",
              ["Cue", "$P_0$", "PE (\\%)", "95\\% CI", "$\\beta_0$", "$\\beta_1$"], rows,
              f"Price-equivalent per cue ({model}, {category}; local-crossing estimator; "
              f"$P_0$=equal-price choice rate; $\\beta_0/\\beta_1$ shown separately; "
              f"* = position quasi-separation).", f"tab:cueprices_{category}")


def crossmodel_table(cues=("sp_strong", "sp_vstrong", "framing_gainloss", "neutral",
                           "scarcity", "authority")):
    files = glob.glob(os.path.join(RESULTS, "M4_validity", "**", "m4_*.csv"), recursive=True)
    models, data = set(), {}
    for f in files:
        if "_mock_" in os.path.basename(f):
            continue
        m, c = _model_of(f), _cue_of(f)
        if not m:
            continue
        models.add(m)
        data.setdefault((c, m), []).append(f)
    if len(models) < 2:
        return
    models = sorted(models)
    rows = []
    for cue in cues:
        row = [cue.replace("_", "\\_")]
        for m in models:
            fs = data.get((cue, m))
            if fs:
                pe = local_crossing_wtp(load_results(sorted(fs)[-1])) * 100
                row.append(f"{pe:.1f}" if np.isfinite(pe) else "--")
            else:
                row.append("--")
        rows.append(row)
    write_tex("tab_crossmodel.tex", ["Cue"] + [m.replace("_", "\\_") for m in models], rows,
              "Price-equivalent (\\%) by cue and model (local-crossing).", "tab:crossmodel")


# ---------- figures ----------
def _style(ax):
    import matplotlib.pyplot as plt  # noqa
    ax.spines["top"].set_visible(False)
    ax.spines["right"].set_visible(False)
    ax.yaxis.grid(True, color=GRID, lw=0.8)
    ax.set_axisbelow(True)


def figures(model="gpt-4o"):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    plt.rcParams.update({"font.size": 11, "axes.edgecolor": MUTED, "axes.linewidth": 0.8})
    os.makedirs(FIGS, exist_ok=True)
    m4 = newest_by(os.path.join(RESULTS, "M4_validity", "**", f"m4_*_{model}_*.csv"), _cue_of)

    # dose-response
    dose = [("sp_weak", "weak"), ("sp_medium", "medium"), ("sp_strong", "strong"),
            ("sp_vstrong", "v.strong")]
    if all(c in m4 for c, _ in dose):
        pes, los, his = [], [], []
        for c, _ in dose:
            r = pe_row(load_results(m4[c]))
            pes.append(r["local"]); los.append(r["local"] - r["lo"]); his.append(r["hi"] - r["local"])
        fig, ax = plt.subplots(figsize=(6, 3.4))
        ax.bar([l for _, l in dose], pes, color=TEAL, width=0.62,
               yerr=[np.abs(los), np.abs(his)], capsize=4, ecolor=MUTED)
        ax.set_ylabel("Price-equivalent (%)"); _style(ax)
        fig.tight_layout(); fig.savefig(os.path.join(FIGS, "fig_dose_response.png"), dpi=160)
        plt.close(fig); print("  fig_dose_response.png")

    # sweep: neutral vs strong social proof
    if "sp_strong" in m4 and "neutral" in m4:
        fig, ax = plt.subplots(figsize=(6, 3.6))
        for cue, col, lab in [("sp_strong", TEAL, "strong social proof"),
                              ("neutral", WARN, "neutral sentence")]:
            d = load_results(m4[cue]); ec = empirical_curve(d)
            ax.plot(ec["price_gap"] * 100, ec["p_nudged"], "o-", color=col, lw=2, ms=6, label=lab)
            ax.axvline(local_crossing_wtp(d) * 100, ls=":", lw=1.2, color=col)
        ax.axhline(0.5, ls="--", lw=1, color=MUTED)
        ax.set_xlabel("Price premium on cued product (%)"); ax.set_ylabel("P(agent chooses cued)")
        ax.set_ylim(0, 1.03); ax.legend(frameon=False, fontsize=10); _style(ax)
        fig.tight_layout(); fig.savefig(os.path.join(FIGS, "fig_sweep_resolution.png"), dpi=160)
        plt.close(fig); print("  fig_sweep_resolution.png")

    # position bias diagnostic (sp_strong)
    if "sp_strong" in m4:
        d = load_results(m4["sp_strong"])
        g = d.groupby("price_gap").agg(P_cued=("chose_nudged", "mean"),
                                       P_first=("picked_primary", "mean")).reset_index()
        fig, ax = plt.subplots(figsize=(6, 3.4))
        ax.plot(g["price_gap"] * 100, g["P_cued"], "o-", color=TEAL, lw=2, ms=6, label="P(chose cued)")
        ax.plot(g["price_gap"] * 100, g["P_first"], "s--", color=WARN, lw=2, ms=6, label="P(chose first slot)")
        ax.axhline(0.5, ls="--", lw=1, color=MUTED)
        ax.set_xlabel("Price premium on cued product (%)"); ax.set_ylabel("Probability")
        ax.set_ylim(0, 1.03); ax.legend(frameon=False, fontsize=10); _style(ax)
        fig.tight_layout(); fig.savefig(os.path.join(FIGS, "fig_position_bias.png"), dpi=160)
        plt.close(fig); print("  fig_position_bias.png")

    # prompt-paraphrase robustness: PE per cue across variants
    e1 = glob.glob(os.path.join(RESULTS, "E1_robustness", "**", f"e1_*_{model}_*.csv"), recursive=True)
    if e1:
        variants = ["v0", "v1", "v2", "v3"]
        series = {}
        for f in e1:
            if "_mock_" in os.path.basename(f):
                continue
            b = os.path.basename(f)
            mv = re.search(r"_(v[0-3])_", b)
            if not mv:
                continue
            v = mv.group(1)
            cue = re.sub(r"^e1_", "", b)
            cue = re.sub(rf"_{v}_.*$", "", cue)
            series.setdefault(cue, {})[v] = f
        if series:
            fig, ax = plt.subplots(figsize=(6, 3.4))
            for cue, vf in sorted(series.items()):
                ys = [local_crossing_wtp(load_results(vf[v])) * 100 if v in vf else np.nan
                      for v in variants]
                ax.plot(variants, ys, "o-", lw=2, ms=6, label=cue.replace("_", " "))
            ax.set_ylabel("Price-equivalent (%)"); ax.set_xlabel("Prompt paraphrase")
            ax.legend(frameon=False, fontsize=8); _style(ax)
            fig.tight_layout(); fig.savefig(os.path.join(FIGS, "fig_robustness.png"), dpi=160)
            plt.close(fig); print("  fig_robustness.png")


def main():
    print("Regenerating paper outputs from data/results/ ...")
    print("Tables:")
    cue_price_table("gpt-4o", "headphones")
    cue_price_table("gpt-4o", "coffee")
    crossmodel_table()
    # Additivity (App. H) is produced by cue_studies/run_additivity.py.
    print("Figures:")
    figures("gpt-4o")
    print("Done. Review figures/ and generated/.")


if __name__ == "__main__":
    main()
